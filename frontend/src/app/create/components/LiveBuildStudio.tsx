function deriveName(hint?: string): string {
  if (!hint) return 'Your Business'
  const words = hint.trim().split(/\s+/).slice(0, 3).filter(w => /^[\p{L}\p{N}'&-]+$/u.test(w))
  if (!words.length) return 'Your Business'
  return words.map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ').slice(0, 26)
}

