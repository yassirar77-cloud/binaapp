/* Lightweight syntax highlighting per file type */
function highlight(text: string, file: number, accent: string) {
  const re =
    file === 0
      ? /(<\/?[a-zA-Z][\w-]*|\/?>|"[^"]*"|<!--[\s\S]*?-->|<!DOCTYPE html>)/g
      : file === 1
        ? /(\/\*[\s\S]*?\*\/|[.#:][\w-]+(?=[\s,{:]|$)|--[\w-]+|@media|\{|\}|"[^"]*")/g
        : /(\/\/.*$|\bconst\b|\blet\b|\bnew\b|\bwindow\b|\bdocument\b|=>|'[^']*'|"[^"]*"|`[^`]*`)/g
  const parts = text.split(re)
  return parts.map((p, i) => {
    if (!p) return null
    let color = '#B8C0E0'
    if (/^(<!--|\/\/|\/\*|<!DOCTYPE)/.test(p)) color = '#4A4A5E'
    else if (/^<\/?[a-zA-Z]/.test(p) || p === '>' || p === '/>') color = '#9D8CFF'
    else if (/^["'`]/.test(p)) color = '#A6E22E'
    else if (/^[.#:@-]|^--/.test(p) && file === 1) color = accent
    else if (/^(const|let|new|window|document|=>)$/.test(p)) color = '#7DCFFF'
    else if (p === '{' || p === '}') color = '#FFB020'
    return <span key={i} style={{ color }}>{p}</span>
  })
}

